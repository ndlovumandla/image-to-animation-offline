import { expect, test } from '@playwright/test'

test('sidebar tools, draggable region timing, millisecond timing and file menu are functional', async ({ page }) => {
  await page.route('**/openverse/v1/audio/**',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({results:[{id:'lesson',title:'Education theme',url:'https://media.test/lesson.wav',creator:'Open artist',license:'cc0'}]})}))
  await page.route('**/commons/w/api.php**',route=>route.fulfill({contentType:'application/json',body:JSON.stringify({query:{pages:[]}})}))
  await page.goto('/')
  const png=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=80;c.height=60;const x=c.getContext('2d')!;x.fillStyle='white';x.fillRect(0,0,80,60);x.fillStyle='black';x.fillRect(20,20,40,20);return c.toDataURL().split(',')[1]})
  await page.getByTestId('image-input').setInputFiles({name:'scene.png',mimeType:'image/png',buffer:Buffer.from(png,'base64')})
  await page.getByRole('button',{name:'Add scene.png to timeline'}).click()
  await expect(page.getByTestId('scene-block')).toHaveCount(1,{timeout:20_000})

  await page.getByRole('button',{name:'Design'}).click()
  const beforeStill=await page.getByTestId('preview-canvas').evaluate((canvas:HTMLCanvasElement)=>canvas.toDataURL())
  await page.getByLabel('Scene 1 sketch enabled').uncheck()
  await expect(page.getByText('The complete image is shown immediately for this scene.')).toBeVisible()
  await expect(page.getByLabel('Scene 1 sketch duration milliseconds')).toBeDisabled()
  await expect(page.getByTestId('sketch-duration-handle')).toHaveCount(0)
  await expect.poll(()=>page.getByTestId('preview-canvas').evaluate((canvas:HTMLCanvasElement)=>canvas.toDataURL())).not.toBe(beforeStill)
  await page.getByLabel('Scene 1 sketch enabled').check()
  await page.getByLabel('Scene 1 duration milliseconds').fill('4321')
  await expect(page.getByLabel('Scene 1 duration milliseconds')).toHaveValue('4321')
  await page.getByLabel('Scene 1 sketch duration milliseconds').fill('1000')
  await expect(page.getByLabel('Scene 1 sketch duration milliseconds')).toHaveValue('1000')
  await page.getByLabel('Scene 1 hand').selectOption('left')

  await page.getByRole('button',{name:/Select sketch sections/}).click()
  await page.getByLabel('Number of sketch regions').fill('2')
  const regionCanvas=page.getByTestId('region-paint-canvas'),regionBox=await regionCanvas.boundingBox()
  if(!regionBox)throw new Error('Region canvas unavailable')
  await page.mouse.move(regionBox.x+regionBox.width*.25,regionBox.y+regionBox.height*.45)
  await page.mouse.down()
  await page.mouse.move(regionBox.x+regionBox.width*.42,regionBox.y+regionBox.height*.55,{steps:8})
  await page.mouse.up()
  await page.getByRole('button',{name:/2\. Region 2/}).click()
  await page.mouse.move(regionBox.x+regionBox.width*.58,regionBox.y+regionBox.height*.45)
  await page.mouse.down()
  await page.mouse.move(regionBox.x+regionBox.width*.75,regionBox.y+regionBox.height*.55,{steps:8})
  await page.mouse.up()
  await page.getByRole('button',{name:'Save regions'}).click()
  await expect(page.getByRole('button',{name:/Select sketch sections \(2\)/})).toBeVisible()
  await expect(page.getByLabel('Scene 1 sketch duration milliseconds')).toBeDisabled()
  await expect(page.getByTestId('sketch-region-segment')).toHaveCount(2)
  await expect(page.getByTestId('sketch-region-boundary')).toHaveCount(1)

  const beforeDrag=await page.evaluate(()=>{const scene=(window as unknown as {__SKETCH_STORE__:{getState():{project:{scenes:Array<{sketchRegions:Array<{duration:number}>}>}}}}).__SKETCH_STORE__.getState().project.scenes[0];return scene.sketchRegions.map(region=>region.duration)})
  const boundary=page.getByTestId('sketch-region-boundary'),boundaryBox=await boundary.boundingBox()
  if(!boundaryBox)throw new Error('Region boundary unavailable')
  await page.mouse.move(boundaryBox.x+boundaryBox.width/2,boundaryBox.y+boundaryBox.height/2)
  await page.mouse.down()
  await page.mouse.move(boundaryBox.x+boundaryBox.width/2+32,boundaryBox.y+boundaryBox.height/2,{steps:6})
  await page.mouse.up()
  const afterDrag=await page.evaluate(()=>{const scene=(window as unknown as {__SKETCH_STORE__:{getState():{project:{scenes:Array<{sketchRegions:Array<{duration:number}>}>}}}}).__SKETCH_STORE__.getState().project.scenes[0];return scene.sketchRegions.map(region=>region.duration)})
  expect(afterDrag[0]).toBeGreaterThan(beforeDrag[0])
  expect(afterDrag[1]).toBeLessThan(beforeDrag[1])
  expect(afterDrag[0]+afterDrag[1]).toBeCloseTo(beforeDrag[0]+beforeDrag[1],8)

  await page.getByLabel('Type video speed').fill('0.75')
  await page.getByLabel('Type video speed').press('Enter')
  await expect(page.getByLabel('Type video speed')).toHaveValue('0.75')
  await expect(page.getByLabel('Current video speed')).toHaveText('0.75×')
  await page.getByRole('button',{name:'Auto speed'}).click()
  await expect(page.getByLabel('Type video speed')).toHaveValue('1')
  await expect(page.getByLabel('Current video speed')).toHaveText('1.00×')
  await expect(page.getByRole('button',{name:'Auto speed'})).toHaveAttribute('aria-pressed','true')
  await page.getByRole('button',{name:'Audio'}).click()
  await page.getByLabel('Search open audio').fill('educational')
  await page.getByLabel('Search open audio').press('Enter')
  await expect(page.getByText('Education theme')).toBeVisible()
  await page.getByRole('button',{name:'File'}).click()
  await expect(page.getByRole('button',{name:'New project'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Save project file'})).toBeVisible()
  await expect(page.getByRole('button',{name:'Share editable copy'})).toBeVisible()
})
